"""Create the schema if it is absent and load the demo data (H17).

    DATABASE_URL="postgresql://..." python -m backend.scripts.seed_db

It applies ``backend/db/schema.sql`` (every statement is idempotent) and then writes the same
eight synthetic patients, their doctor assignments, conditions, medications and observations,
plus the demo user accounts, that the in-memory demo serves. Running it twice is safe.

Nothing here is clinical data: every patient is generated by ``backend/app/data/synthetic.py``.
"""

from __future__ import annotations

import argparse
import logging
import sys
from datetime import date
from pathlib import Path
from typing import Any

from backend.app.config import Settings
from backend.app.data.repository import SyntheticRepository
from backend.app.data.synthetic import DOCTORS
from backend.app.db import queries, rows
from backend.app.db.engine import create_engine
from backend.app.users import seed_demo_users

SCHEMA_FILE = Path(__file__).resolve().parents[1] / "db" / "schema.sql"
logger = logging.getLogger("seed_db")


def apply_schema(engine: Any, schema_file: Path = SCHEMA_FILE) -> None:
    """Run schema.sql as one transaction. Safe to repeat."""
    from sqlalchemy import text

    with engine.begin() as connection:
        connection.execute(text(schema_file.read_text(encoding="utf-8")))


def seed(engine: Any, password: str) -> dict[str, int]:
    """Write the synthetic patients and demo accounts. Returns what was written."""
    from sqlalchemy import text

    repo = SyntheticRepository()
    patients = repo.list_all()
    users = seed_demo_users(repo, password).all()

    with engine.begin() as connection:
        for patient in patients:
            connection.execute(text(queries.INSERT_PATIENT), rows.patient_params(patient))
            connection.execute(
                text(queries.INSERT_ASSIGNMENT),
                {"doctor_id": patient.assigned_doctor, "patient_id": patient.id},
            )
            for condition_id in patient.conditions:
                connection.execute(
                    text(queries.INSERT_CONDITION),
                    {"patient_id": patient.id, "condition_id": condition_id},
                )
            # Replace the child rows rather than growing them on a second run.
            connection.execute(text(queries.DELETE_MEDICATIONS), {"patient_id": patient.id})
            connection.execute(text(queries.DELETE_OBSERVATIONS), {"patient_id": patient.id})
            connection.execute(
                text(queries.INSERT_MEDICATION),
                [
                    {
                        "patient_id": patient.id,
                        "name": m.name,
                        "dose": m.dose,
                        "frequency": m.frequency,
                        "started": date.fromisoformat(m.started),
                    }
                    for m in patient.medications
                ],
            )
            connection.execute(
                text(queries.INSERT_OBSERVATION),
                [
                    {
                        "patient_id": patient.id,
                        "observed_on": date.fromisoformat(o.date),
                        "bmi": o.bmi,
                        "systolic_bp": o.systolic_bp,
                        "hba1c": o.hba1c,
                    }
                    for o in patient.observations
                ],
            )
        for user in users:
            connection.execute(text(queries.INSERT_USER), rows.user_params(user))

    return {"patients": len(patients), "users": len(users), "doctors": len(DOCTORS)}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Create the schema and load the demo data.")
    parser.add_argument("--database-url", default="", help="default: DATABASE_URL in the env")
    parser.add_argument("--schema-only", action="store_true", help="create tables, load nothing")
    args = parser.parse_args(argv)

    logging.basicConfig(level=logging.INFO, format="%(message)s")
    settings = Settings()
    url = args.database_url or settings.database_url
    if not url:
        logger.error("no database: set DATABASE_URL (or pass --database-url)")
        return 2

    engine = create_engine(url)
    apply_schema(engine)
    logger.info("schema applied from %s", SCHEMA_FILE)
    if args.schema_only:
        return 0
    written = seed(engine, settings.effective_demo_password)
    logger.info(
        "seeded %(patients)s patients and %(users)s accounts across %(doctors)s doctors", written
    )
    logger.info("start the API with the same DATABASE_URL set to use it")
    return 0


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
